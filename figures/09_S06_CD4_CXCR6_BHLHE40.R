# p_val_adj floored before -log10() so genes with p_val_adj == 0 don't produce Inf.
de_volcano_df <- de_hihi_vs_lolo %>%
  mutate(
    gene = rownames(de_hihi_vs_lolo),
    neg_log10_padj = -log10(pmax(p_val_adj, 1e-300)),
    sig = case_when(
      p_val_adj < 0.05 & avg_log2FC >  1 ~ "Up in hi/hi",
      p_val_adj < 0.05 & avg_log2FC < -1 ~ "Up in lo/lo",
      TRUE ~ "NS"
    )
  )

# Label the top 10 genes by adjusted p-value or absolute log2 fold change.
volcano_labels <- bind_rows(
  de_volcano_df %>% slice_min(p_val_adj, n = 10),
  de_volcano_df %>% slice_max(abs(avg_log2FC), n = 10)
) %>%
  distinct(gene, .keep_all = TRUE)

volcano_grid_theme <- theme(
  panel.grid.major = element_line(color = "grey90"),
  panel.grid.minor = element_blank(),
