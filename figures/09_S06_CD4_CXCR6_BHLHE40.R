# Draw grey background cells before highlighted cells.
make_group_umap <- function(group_name) {
  group_clusters <- names(cluster_to_group)[cluster_to_group == group_name]
  
  plot_df <- get_umap_df(cd4)
  plot_df$is_highlight <- plot_df$cluster_id %in% group_clusters
  plot_df$point_color <- ifelse(plot_df$is_highlight, cluster_colors[plot_df$cluster_id], "grey85")
  plot_df <- plot_df[c(which(!plot_df$is_highlight), sample(which(plot_df$is_highlight))), ]
  
  ggplot(plot_df, aes(x = UMAP_1, y = UMAP_2, color = point_color)) +
    geom_point(size = 0.1) +
    scale_color_identity() +
    geom_text(
      data = cluster_centroids %>% filter(cluster_id %in% group_clusters),
      aes(x = UMAP_1, y = UMAP_2, label = cluster_id),
      inherit.aes = FALSE, size = panel_label_size
    ) +
    theme_void() +
    theme(aspect.ratio = 1, legend.position = "none")
}

