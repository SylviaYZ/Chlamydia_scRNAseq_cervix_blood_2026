# Compute Spearman correlation and optionally export a regression plot.
plot_burden_correlation <- function(per_patient, y_col, y_label, rds_name, jpg_name = NULL, save_plot = TRUE) {
  cor_test <- cor.test(per_patient[[y_col]], per_patient$log10_burden, method = "spearman")
  saveRDS(cor_test, file.path(out_dir, rds_name))
  
  if (save_plot) {
    stat_label <- sprintf("Spearman ρ = %.2f\np = %.3g", cor_test$estimate, cor_test$p.value)
    
    p <- ggplot(per_patient, aes(x = log10_burden, y = .data[[y_col]])) +
      geom_point(size = 2) +
      geom_smooth(method = "lm", se = TRUE) +
      annotate("text", x = Inf, y = -Inf, label = stat_label, hjust = 1.05, vjust = -0.3, size = 3.5) +
      theme_classic() +
      labs(x = "log10(chlamydial burden)", y = y_label)
    ggsave(file.path(out_dir, jpg_name), p, width = 5, height = 4, dpi = 600)
  }
  invisible(cor_test)
}

