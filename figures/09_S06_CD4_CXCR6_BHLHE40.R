# Build the lo/hi axis tables used by panels E, H and I.
make_axis_table <- function(df, text_pt = panel_pt, facet = FALSE) {
  p <- ggplot(df, aes(x = x, y = gene, label = level)) +
    geom_text(size = pt_to_mm(text_pt)) +
    labs(x = NULL, y = NULL) +
    theme_minimal() +
    theme(
      axis.text.x = element_blank(),
      axis.text.y = element_text(size = text_pt, color = "black"),
      axis.ticks = element_blank(),
      panel.grid = element_blank(),
      plot.margin = margin(0, 1, 1, 1, unit = "pt")
    )
  if (facet) {
    p <- p + facet_wrap(~ family, nrow = 1) +
      theme(strip.text = element_blank(), strip.background = element_blank())
  }
  p
}

